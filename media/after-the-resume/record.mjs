import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {writeFile} from 'node:fs/promises';
import {dirname,join} from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {finalizeWebm} from './finalize-webm.mjs';
const root=dirname(fileURLToPath(import.meta.url));
const browser=await chromium.launch({headless:true,channel:'msedge'});
const page=await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.addInitScript(()=>{const C=window.AudioContext||window.webkitAudioContext;const create=C.prototype.createGain;C.prototype.createGain=function(){const gain=create.call(this);window.__recordAudio=this.createMediaStreamDestination();gain.connect(window.__recordAudio);return gain}});
await page.goto(pathToFileURL(join(root,'index.html')).href);
await page.waitForSelector('html[data-ready=true]');
await page.locator('#play').click();await page.waitForFunction(()=>window.TalentFilm.getState().audioReady);
const config=await page.evaluate(()=>{
  window.TalentFilm.pause();window.TalentFilm.seek(0);
  const codecs=['video/webm;codecs=vp9,opus','video/webm;codecs=vp8,opus','video/webm'];
  const mimeType=codecs.find(type=>MediaRecorder.isTypeSupported(type));if(!mimeType)throw new Error('No WebM encoder available');
  const stream=document.querySelector('canvas').captureStream(30);window.__recordAudio.stream.getAudioTracks().forEach(track=>stream.addTrack(track));
  const recorder=new MediaRecorder(stream,{mimeType,videoBitsPerSecond:4500000,audioBitsPerSecond:128000});const chunks=[];
  recorder.ondataavailable=e=>{if(e.data.size)chunks.push(e.data)};
  recorder.onerror=e=>{window.__recordError=String(e.error)};
  recorder.onstop=()=>{const reader=new FileReader();reader.onload=()=>{window.__recordData=reader.result};reader.readAsDataURL(new Blob(chunks,{type:mimeType}))};
  window.__recorder=recorder;window.__recordStream=stream;recorder.start(1000);window.TalentFilm.play();
  return {mimeType,width:1920,height:1080,fps:30,audioTracks:stream.getAudioTracks().length};
});
console.log('Recording complete playback: '+JSON.stringify(config));
const start=Date.now();
await page.waitForFunction(()=>window.TalentFilm.getState().time>=96&&!window.TalentFilm.getState().playing,null,{timeout:125000});
const elapsedMs=Date.now()-start;
const state=await page.evaluate(()=>{window.__recorder.stop();return window.TalentFilm.getState()});
await page.waitForFunction(()=>Boolean(window.__recordData)||Boolean(window.__recordError),null,{timeout:20000});
assert.equal(await page.evaluate(()=>window.__recordError||''),'');
const data=await page.evaluate(()=>window.__recordData);const buffer=Buffer.from(data.slice(data.indexOf(';base64,')+8),'base64');
await writeFile(join(root,'简历之后.webm'),buffer);
const container=await finalizeWebm(join(root,'简历之后.webm'),96);
await page.evaluate(()=>{window.__recordStream.getTracks().forEach(track=>track.stop());window.__recordAudio.disconnect()});
assert.equal(state.time,96);assert.equal(state.playing,false);assert.deepEqual(errors,[]);assert(buffer.length>100000);
await writeFile(join(root,'qa','playback.json'),JSON.stringify({date:new Date().toISOString(),...config,elapsedMs,...container,ending:state,errors},null,2));
console.log(JSON.stringify({elapsedMs,...container,ending:state,errors},null,2));await browser.close();
